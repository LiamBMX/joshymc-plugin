package com.liam.joshymc.bedrock

import com.google.gson.JsonArray
import com.google.gson.JsonObject
import java.io.ByteArrayOutputStream
import java.security.MessageDigest
import java.time.LocalDateTime
import java.util.zip.CRC32
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * The Bedrock resource pack (.mcpack) Geyser sends to Bedrock players (issue #1314),
 * Bukkit-free. It only holds what the Geyser mappings point at: one icon per mapped item
 * under `textures/<namespace>/` and `textures/item_texture.json` naming them.
 *
 * The bytes are deterministic (sorted entries, fixed timestamps), and the manifest's pack
 * and module UUIDs never change, so Bedrock clients keep their cached copy. The version
 * is derived from the content, so any change is a new version they download once.
 */
object BedrockPack {

    const val PACK_NAME = "JoshyMC Custom Items"
    private const val HEADER_UUID = "9531da25-6c4e-4d8f-b582-b229982b9ea8"
    private const val MODULE_UUID = "278fcd91-ad30-43e6-95ba-2afcb6765945"
    /** The earliest zip time, set as local time so the server's timezone can't change the bytes. */
    private val ZIP_TIME: LocalDateTime = LocalDateTime.of(1980, 1, 1, 0, 0)

    /**
     * [icons] is Bedrock texture key -> icon path in the JAR (`joshymc/frostbite.png`);
     * [readIcon] loads those bytes. Returns the .mcpack bytes.
     */
    fun build(icons: Map<String, String>, readIcon: (String) -> ByteArray): ByteArray {
        val files = sortedMapOf<String, ByteArray>()
        val textureData = JsonObject()
        for ((key, path) in icons.toSortedMap()) {
            val texture = "textures/${path.removeSuffix(".png")}" // icon paths start with their namespace
            files["$texture.png"] = readIcon(path)
            textureData.add(key, JsonObject().apply { addProperty("textures", texture) })
        }
        val itemTexture = JsonObject().apply {
            addProperty("resource_pack_name", "joshymc")
            addProperty("texture_name", "atlas.items")
            add("texture_data", textureData)
        }
        files["textures/item_texture.json"] = json(itemTexture)
        files["manifest.json"] = json(manifest(version(files)))
        return zip(files)
    }

    /** `[1, a, b]` from a hash of every other file, each part a small positive int. */
    fun version(files: Map<String, ByteArray>): IntArray {
        val digest = MessageDigest.getInstance("SHA-1")
        for ((name, bytes) in files.toSortedMap()) {
            digest.update(name.toByteArray())
            digest.update(0)
            digest.update(bytes)
        }
        val h = digest.digest()
        val a = ((h[0].toInt() and 0xFF) shl 8) or (h[1].toInt() and 0xFF)
        val b = ((h[2].toInt() and 0xFF) shl 8) or (h[3].toInt() and 0xFF)
        return intArrayOf(1, a, b)
    }

    private fun manifest(version: IntArray): JsonObject {
        fun versionArray() = JsonArray().apply { version.forEach { add(it) } }
        val header = JsonObject().apply {
            addProperty("name", PACK_NAME)
            addProperty("description", "JoshyMC custom item icons for Bedrock players (generated by the JoshyMC plugin)")
            addProperty("uuid", HEADER_UUID)
            add("version", versionArray())
            add("min_engine_version", JsonArray().apply { add(1); add(21); add(0) })
        }
        val module = JsonObject().apply {
            addProperty("type", "resources")
            addProperty("uuid", MODULE_UUID)
            add("version", versionArray())
        }
        return JsonObject().apply {
            addProperty("format_version", 2)
            add("header", header)
            add("modules", JsonArray().apply { add(module) })
        }
    }

    private fun json(o: JsonObject) = (GeyserMappings.GSON.toJson(o) + "\n").toByteArray(Charsets.UTF_8)

    private fun zip(files: Map<String, ByteArray>): ByteArray {
        val out = ByteArrayOutputStream()
        ZipOutputStream(out).use { zip ->
            for ((name, bytes) in files) {
                val entry = ZipEntry(name)
                entry.timeLocal = ZIP_TIME
                entry.size = bytes.size.toLong()
                entry.crc = CRC32().apply { update(bytes) }.value
                zip.putNextEntry(entry)
                zip.write(bytes)
                zip.closeEntry()
            }
        }
        return out.toByteArray()
    }
}
